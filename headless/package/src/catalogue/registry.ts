const rule = (
  value: Pick<
    Rule,
    | 'ruleId'
    | 'title'
    | 'description'
    | 'family'
    | 'severity'
    | 'mutationClass'
    | 'mutationBoundary'
    | 'transitionSequence'
    | 'oracle'
    | 'interaction'
    | 'templateId'
  > &
    Partial<
      Pick<Rule, 'applicability' | 'scope' | 'exclusions' | 'supported' | 'unsupportedReason'>
    >
): Rule => ({
  ...value,
  applicability: value.applicability ?? {
    sourceKinds: ['任意可写基础字段'],
    targetKinds: [],
    relationshipKinds: [],
    predicate: '模板声明了规则所需字段，且运行适配器支持对应操作',
  },
  scope: value.scope ?? ['无并发写入的单工作区、单次确定性操作序列'],
  exclusions: value.exclusions ?? ['公式语言的全部表达式组合', '权限、自动化和宿主界面行为'],
  supported: value.supported ?? true,
});

